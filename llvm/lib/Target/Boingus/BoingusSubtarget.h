// Boingus has a single variant, so the Subtarget just owns the per-target
// helper classes (InstrInfo, RegisterInfo, TargetLowering, FrameLowering) and
// hands them out to the code generator.
//
//===----------------------------------------------------------------------===//

#ifndef LLVM_LIB_TARGET_BOINGUS_BOINGUSSUBTARGET_H
#define LLVM_LIB_TARGET_BOINGUS_BOINGUSSUBTARGET_H

#include "BoingusFrameLowering.h"
#include "BoingusISelLowering.h"
#include "BoingusInstrInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "BoingusGenSubtargetInfo.inc"

namespace llvm {

class StringRef;
class TargetMachine;
class Triple;

class BoingusSubtarget : public BoingusGenSubtargetInfo {
  virtual void anchor();

  // Order matters: members are constructed top to bottom, and TLInfo's
  // constructor asks for the RegisterInfo that lives inside InstrInfo.
  BoingusInstrInfo InstrInfo;
  BoingusFrameLowering FrameLowering;
  BoingusTargetLowering TLInfo;

public:
  BoingusSubtarget(const Triple &TT, const std::string &CPU,
                   const std::string &FS, const TargetMachine &TM);

  // Generated by TableGen from the features in Boingus.td.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  // The code generator reaches the helper classes through these.
  const BoingusInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const BoingusRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const BoingusFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const BoingusTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_BOINGUS_BOINGUSSUBTARGET_H
